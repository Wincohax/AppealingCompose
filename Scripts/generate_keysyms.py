#!/usr/bin/env python3
"""
Generates AppealingCompose/src/Composer/Headers/KeysymTable.hpp from X11's keysymdef.h.

Usage:
    curl -sL -o /tmp/keysymdef.h \
        https://gitlab.freedesktop.org/xorg/proto/xorgproto/-/raw/master/include/X11/keysymdef.h
    python3 Scripts/generate_keysyms.py /tmp/keysymdef.h

Every keysym with a Unicode equivalent in keysymdef.h ends up in the table, so the
parser can turn tokens like <Cyrillic_a> or <KP_Add> into the character macOS sends.
"""

import re
import sys
from pathlib import Path

DEFINE = re.compile(r"^#define XK_([A-Za-z0-9_]+)\s+0x([0-9a-fA-F]+)\s*(?:/\*(.*?)\*/)?")
# "U+0430 ..." exact, "<U+002B ...>" equivalent, "(U+2010 ...)" deprecated/ambiguous
UNICODE = re.compile(r"^\s*([<(]?)U\+([0-9A-Fa-f]{4,6})")
ALIAS = re.compile(r"alias for ([A-Za-z0-9_]+)")


def main(source: str) -> None:
    exact: dict[str, int] = {}
    fallback: dict[str, int] = {}
    aliases: dict[str, str] = {}

    for line in Path(source).read_text(encoding="utf-8").splitlines():
        match = DEFINE.match(line)
        if not match:
            continue
        name, value, comment = match.group(1), int(match.group(2), 16), match.group(3) or ""

        if code := UNICODE.match(comment):
            target = exact if code.group(1) == "" else fallback
            target.setdefault(name, int(code.group(2), 16))
        elif 0x01000100 <= value <= 0x0110FFFF:
            # Unicode keysyms encode the code point directly
            exact.setdefault(name, value - 0x01000000)
        elif alias := ALIAS.search(comment):
            # e.g. Ooblique: "deprecated alias for Oslash"
            aliases[name] = alias.group(1)

    table = {**fallback, **exact}
    for name, target in aliases.items():
        if name not in table and target in table:
            table[name] = table[target]

    out = Path(__file__).resolve().parent.parent / "AppealingCompose/src/Composer/Headers/KeysymTable.hpp"
    lines = [
        "//",
        "//  KeysymTable.hpp",
        "//  AppealingCompose",
        "//",
        "//  GENERATED by Scripts/generate_keysyms.py from X11 keysymdef.h. Do not edit by hand.",
        "//",
        "",
        "#ifndef KeysymTable_hpp",
        "#define KeysymTable_hpp",
        "",
        "#include <string_view>",
        "#include <unordered_map>",
        "",
        "// X11 keysym name -> Unicode code point",
        "inline const std::unordered_map<std::string_view, char32_t> keysymTable {",
    ]
    lines += [f'    {{"{name}", 0x{cp:04X}}},' for name, cp in sorted(table.items())]
    lines += ["};", "", "#endif /* KeysymTable_hpp */", ""]
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {len(table)} keysyms to {out}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "/tmp/keysymdef.h")
